// Expand the compact beat spec above into the full toBeatBankEntry shape.
export function expandBeat(b) {
  const loop = LOOPS[b.loop];
  return {
    id: b.id,
    title: b.title,
    artist: b.artist,
    artwork: null, // carousel falls back to its placeholder pattern
    audioUrl: loop.url,
    bank: b.producerId,
    file: loop.url,
    previewState: "ready",
    previewMode: "platform",
    isFree: b.isFree ?? false,
    freeTerms: b.isFree ? "Free — use in any capacity." : null,
    // A real buy_url would point at Gumroad; the demo intercepts the buy
    // action instead (see demo-store.buildBuyUrl), so a sentinel is enough.
    buyUrl: b.isFree ? null : `demo://buy/${b.id}`,
    peaks: loop.peaks,
    bpm: b.bpm,
    musicalKey: b.musicalKey,
    tags: b.tags || [],
    producerId: b.producerId,
    rightsHolderId: b.rightsHolderId,
    status: "published",
    withdrawnAt: null,
    containsSamples: false,
    tradable: !b.isFree,
    licenses: b.isFree ? [] : tiers(b.id, b.prices),
  };
}

